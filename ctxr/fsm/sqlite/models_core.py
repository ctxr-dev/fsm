class LockTable(SQLModel, table=True):
    """A single-row-per-run advisory lock used by the engine to serialise writers.

    ``run_id`` is *both* the primary key and a FK into ``runs.id`` — there
    is at most one lock per run at any moment. ``expires_at`` is the lease
    expiry; the engine treats a lock with ``expires_at <= now()`` as
    reclaimable.
    """

    __tablename__ = "locks"
    __table_args__ = (_SQLITE_DIALECT_KWARGS,)

    run_id: str = Field(
        sa_column=Column(
            "run_id",
            Text,
            ForeignKey("runs.id", ondelete="CASCADE"),
            primary_key=True,
            nullable=False,
        ),
    )
    holder_session_id: str = Field(
        sa_column=Column("holder_session_id", Text, nullable=False),
    )
    acquired_at: str = Field(
        sa_column=Column("acquired_at", Text, nullable=False),
    )
    expires_at: str = Field(
        sa_column=Column("expires_at", Text, nullable=False),
    )


